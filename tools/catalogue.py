#!/usr/bin/env python3
"""The module catalogue: add-ons that live in their own repositories.

Studio, Data, Flow, the assistant and the SQL source ship their add-on bundle in
their own repository (`deploy/papaia-addon/`). `catalogue.yaml` at the root of
this repository lists them, each pinned to one bundle:

* `version`, `description`, `requires` are copied from the bundle's
  `papaia-app.yaml` at the pinned commit (`requires.addons` normalised to
  `{name, optional}`, plus `version` where the manifest names a range);
* `source` names the repository (https URL), the full commit and the bundle path;
* `digest` is the bundle digest `sha256:<hex>`: SHA-256 over one line
  `<mode> <sha256 of the file> <path>\\n` per file of the bundle, sorted by path,
  where mode is `100644` or `100755` and path is relative to the bundle. Symbolic
  links and submodules are refused, so a copy of the bundle is exactly its
  regular files. The compose file is part of the bundle, so the image pins
  (tag and digest) of the module are covered by the digest as well.

Every input is checked with explicit type checks; unknown fields are refused.

Commands:
  check     the catalogue is valid and in canonical form (components.py check runs it)
  list      name, version, description and prerequisites of every entry
  pin       write one entry from a clone of the module repository (default: its HEAD)
  verify    compare entries with clones of the module repositories
  fetch     copy one bundle out of a clone of its repository after checking its digest
  matrix    compare the versions with the core's compatibility matrix (compat/suite.yaml)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import stat
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = "catalogue.yaml"
SCHEMA = "papaia.addon-catalogue/1"
MANIFEST = "papaia-app.yaml"
MAX_BYTES = 256 * 1024
MAX_ENTRIES = 64
MAX_FILES = 512
MAX_FILE_BYTES = 4 * 1024 * 1024
MAX_BUNDLE_BYTES = 16 * 1024 * 1024

HEADER = """\
# Module catalogue: add-ons that live in their own repositories, each pinned to
# one bundle by version, commit and bundle digest. Generated by
# `python tools/catalogue.py pin`; do not edit by hand. Contract: docs/development.md.
"""

TOP_FIELDS = ("schema", "entries")
ENTRY_FIELDS = ("name", "title", "version", "description", "requires", "source", "digest")
REQUIRES_FIELDS = ("addon_api", "papaia_compat", "addons")
REQUIRES_MANDATORY = ("addon_api", "papaia_compat")
ADDON_FIELDS = ("name", "version", "optional")
SOURCE_FIELDS = ("repo", "commit", "path")
FILE_MODES = ("100644", "100755")

NAME_RE = re.compile(r"\A[a-z0-9][a-z0-9-]{0,63}\Z")
VERSION_RE = re.compile(r"\A(\d+)\.(\d+)\.(\d+)\Z")
COMMIT_RE = re.compile(r"\A[0-9a-f]{40}\Z")
DIGEST_RE = re.compile(r"\Asha256:[0-9a-f]{64}\Z")
PATH_PART_RE = re.compile(r"\A[A-Za-z0-9_][A-Za-z0-9._-]{0,127}\Z")
HOST_RE = re.compile(r"\A[a-z0-9]([a-z0-9.-]{0,251}[a-z0-9])?\Z")
URL_PATH_RE = re.compile(r"\A(/[A-Za-z0-9._-]{1,100}){1,8}\Z")
CONSTRAINT_RE = re.compile(r"\A(>=|<=|>|<|==)(\d+\.\d+\.\d+)\Z")
MAX_TITLE = 40
MAX_DESCRIPTION = 200


class CatalogueError(Exception):
    """A catalogue, a bundle or a repository that cannot be used."""


@dataclass(frozen=True)
class BundleFile:
    path: str
    mode: str
    data: bytes


# ---------------------------------------------------------------------------
# Reading and validating


def load(path: Path) -> dict[str, Any]:
    """The catalogue at `path`: a regular file of at most MAX_BYTES holding a mapping."""
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NONBLOCK", 0))
    except OSError as exc:
        raise CatalogueError(f"{path}: cannot be read ({exc.strerror})") from exc
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise CatalogueError(f"{path}: not a regular file")
        raw = b""
        while len(raw) <= MAX_BYTES:
            chunk = os.read(fd, MAX_BYTES + 1 - len(raw))
            if not chunk:
                break
            raw += chunk
    finally:
        os.close(fd)
    if len(raw) > MAX_BYTES:
        raise CatalogueError(f"{path}: larger than {MAX_BYTES} bytes")
    try:
        loaded = yaml.safe_load(raw.decode("utf-8"))
    except (UnicodeDecodeError, yaml.YAMLError) as exc:
        raise CatalogueError(f"{path}: not valid YAML ({exc.__class__.__name__})") from exc
    if not isinstance(loaded, dict):
        raise CatalogueError(f"{path}: not a mapping")
    return loaded


def _unknown(where: str, value: dict[str, Any], allowed: tuple[str, ...]) -> list[str]:
    extra = sorted(str(key) for key in value if key not in allowed)
    return [f"{where}: unknown field {', '.join(extra)}"] if extra else []


def _missing(where: str, value: dict[str, Any], required: tuple[str, ...]) -> list[str]:
    absent = [key for key in required if key not in value]
    return [f"{where}: missing field {', '.join(absent)}"] if absent else []


def _text(value: object, limit: int) -> bool:
    return (
        isinstance(value, str)
        and 0 < len(value) <= limit
        and value == value.strip()
        and value.isprintable()
    )


def valid_constraint(value: object) -> bool:
    if not isinstance(value, str) or not 0 < len(value) <= 64:
        return False
    return all(CONSTRAINT_RE.match(part) for part in value.split(","))


def valid_bundle_path(value: object) -> bool:
    if not isinstance(value, str) or not 0 < len(value) <= 255:
        return False
    return all(PATH_PART_RE.match(part) for part in value.split("/"))


def valid_repo_url(value: object) -> bool:
    """An https URL without credentials, port, query or fragment."""
    if not isinstance(value, str) or not 0 < len(value) <= 255:
        return False
    parts = urlsplit(value)
    return (
        parts.scheme == "https"
        and parts.netloc == parts.hostname
        and bool(parts.hostname and HOST_RE.match(parts.hostname))
        and bool(URL_PATH_RE.match(parts.path))
        and not parts.query
        and not parts.fragment
        and value == f"https://{parts.netloc}{parts.path}"
    )


def _check_requires(where: str, requires: object) -> list[str]:
    if not isinstance(requires, dict):
        return [f"{where}: requires must be a mapping"]
    problems = _unknown(f"{where}.requires", requires, REQUIRES_FIELDS)
    problems += _missing(f"{where}.requires", requires, REQUIRES_MANDATORY)
    api = requires.get("addon_api")
    if "addon_api" in requires and not (
        isinstance(api, list)
        and 0 < len(api) <= 16
        and all(isinstance(g, int) and not isinstance(g, bool) and 0 < g < 1000 for g in api)
    ):
        problems.append(f"{where}.requires.addon_api: a list of contract generations")
    if "papaia_compat" in requires and not valid_constraint(requires.get("papaia_compat")):
        problems.append(f"{where}.requires.papaia_compat: a range such as >=1.10.0")
    if "addons" not in requires:
        return problems
    addons = requires["addons"]
    if not isinstance(addons, list) or len(addons) > 16:
        return [*problems, f"{where}.requires.addons: a list of at most 16 entries"]
    for index, neighbour in enumerate(addons):
        label = f"{where}.requires.addons[{index}]"
        if not isinstance(neighbour, dict):
            problems.append(f"{label}: a mapping with name and optional")
            continue
        problems += _unknown(label, neighbour, ADDON_FIELDS)
        problems += _missing(label, neighbour, ("name", "optional"))
        if "name" in neighbour and not (
            isinstance(neighbour["name"], str) and NAME_RE.match(neighbour["name"])
        ):
            problems.append(f"{label}.name: lower-case add-on name")
        if "optional" in neighbour and not isinstance(neighbour["optional"], bool):
            problems.append(f"{label}.optional: true or false")
        if "version" in neighbour and not valid_constraint(neighbour["version"]):
            problems.append(f"{label}.version: a range such as >=0.1.0")
    return problems


def _check_source(where: str, source: object) -> list[str]:
    if not isinstance(source, dict):
        return [f"{where}: source must be a mapping"]
    problems = _unknown(f"{where}.source", source, SOURCE_FIELDS)
    problems += _missing(f"{where}.source", source, SOURCE_FIELDS)
    if "repo" in source and not valid_repo_url(source["repo"]):
        problems.append(f"{where}.source.repo: an https URL without credentials, port or query")
    if "commit" in source and not (
        isinstance(source["commit"], str) and COMMIT_RE.match(source["commit"])
    ):
        problems.append(f"{where}.source.commit: a full commit id (40 lower-case hex digits)")
    if "path" in source and not valid_bundle_path(source["path"]):
        problems.append(f"{where}.source.path: a relative path without `..`")
    return problems


def _check_entry(where: str, item: object) -> list[str]:
    if not isinstance(item, dict):
        return [f"{where}: must be a mapping"]
    problems = _unknown(where, item, ENTRY_FIELDS) + _missing(where, item, ENTRY_FIELDS)
    if "name" in item and not (isinstance(item["name"], str) and NAME_RE.match(item["name"])):
        problems.append(f"{where}.name: lower-case add-on name of at most 64 characters")
    if "title" in item and not _text(item["title"], MAX_TITLE):
        problems.append(f"{where}.title: one line of at most {MAX_TITLE} characters")
    if "version" in item and not (
        isinstance(item["version"], str) and VERSION_RE.match(item["version"])
    ):
        problems.append(f"{where}.version: X.Y.Z")
    if "description" in item and not _text(item["description"], MAX_DESCRIPTION):
        problems.append(f"{where}.description: one line of at most {MAX_DESCRIPTION} characters")
    if "digest" in item and not (isinstance(item["digest"], str) and DIGEST_RE.match(item["digest"])):
        problems.append(f"{where}.digest: sha256:<64 lower-case hex digits>")
    if "requires" in item:
        problems += _check_requires(where, item["requires"])
    if "source" in item:
        problems += _check_source(where, item["source"])
    return problems


def validate(doc: object, local_addons: set[str]) -> list[str]:
    """Every problem of a catalogue document; `local_addons` are the add-on directories
    of this repository, whose names an entry must not take."""
    if not isinstance(doc, dict):
        return ["catalogue: not a mapping"]
    problems = _unknown("catalogue", doc, TOP_FIELDS) + _missing("catalogue", doc, TOP_FIELDS)
    if "schema" in doc and doc["schema"] != SCHEMA:
        problems.append(f"catalogue: schema must be {SCHEMA}")
    entries = doc.get("entries")
    if "entries" in doc and (not isinstance(entries, list) or len(entries) > MAX_ENTRIES):
        return [*problems, f"catalogue: entries must be a list of at most {MAX_ENTRIES}"]
    seen: set[str] = set()
    for index, item in enumerate(entries or []):
        where = f"entries[{index}]"
        problems += _check_entry(where, item)
        name = item.get("name") if isinstance(item, dict) else None
        if not isinstance(name, str):
            continue
        if name in seen:
            problems.append(f"{where}: {name} is listed twice")
        seen.add(name)
        if name in local_addons:
            problems.append(f"{where}: {name} is also an add-on directory of this repository")
    return problems


def local_addons(root: Path) -> set[str]:
    return {p.name for p in root.iterdir() if p.is_dir() and (p / MANIFEST).is_file()}


def check(root: Path) -> list[str]:
    """Problems of `catalogue.yaml` under `root`; empty when it is valid and canonical."""
    path = root / CATALOGUE
    try:
        doc = load(path)
    except CatalogueError as exc:
        return [str(exc)]
    problems = validate(doc, local_addons(root))
    if problems:
        return problems
    if path.read_text(encoding="utf-8") != render(doc):
        return [f"{CATALOGUE}: not in canonical form; rewrite it with `python tools/catalogue.py pin`"]
    return []


# ---------------------------------------------------------------------------
# Writing


def _scalar(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(value, ensure_ascii=False)


def _flow_mapping(value: dict[str, Any]) -> str:
    return "{" + ", ".join(f"{key}: {_scalar(item)}" for key, item in value.items()) + "}"


def render(doc: dict[str, Any]) -> str:
    """The canonical text of a valid catalogue document."""
    lines = [HEADER.rstrip("\n"), f"schema: {doc['schema']}"]
    entries = doc["entries"]
    if not entries:
        lines.append("entries: []")
        return "\n".join(lines) + "\n"
    lines.append("entries:")
    for item in entries:
        requires = item["requires"]
        source = item["source"]
        lines += [
            f"  - name: {item['name']}",
            f"    title: {_scalar(item['title'])}",
            f"    version: {_scalar(item['version'])}",
            f"    description: {_scalar(item['description'])}",
            "    requires:",
            f"      addon_api: [{', '.join(str(g) for g in requires['addon_api'])}]",
            f"      papaia_compat: {_scalar(requires['papaia_compat'])}",
        ]
        if "addons" in requires:
            if requires["addons"]:
                lines.append("      addons:")
                lines += [f"        - {_flow_mapping(n)}" for n in requires["addons"]]
            else:
                lines.append("      addons: []")
        lines += [
            "    source:",
            f"      repo: {source['repo']}",
            f"      commit: {_scalar(source['commit'])}",
            f"      path: {source['path']}",
            f"    digest: {_scalar(item['digest'])}",
        ]
    return "\n".join(lines) + "\n"


def write(root: Path, doc: dict[str, Any]) -> None:
    problems = validate(doc, local_addons(root))
    if problems:
        raise CatalogueError("; ".join(problems))
    target = root / CATALOGUE
    fd, tmp = tempfile.mkstemp(dir=root, prefix=".catalogue-", suffix=".yaml")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(render(doc))
        os.chmod(tmp, 0o644)
        os.replace(tmp, target)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


# ---------------------------------------------------------------------------
# Bundles in git


def _git(repo: Path, *args: str) -> bytes:
    command = ["git", "-c", "core.fsmonitor=false", "-C", str(repo), *args]
    try:
        result = subprocess.run(command, check=False, capture_output=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise CatalogueError(f"{repo}: git failed ({exc.__class__.__name__})") from exc
    if result.returncode != 0:
        raise CatalogueError(f"{repo}: git {args[0]} failed")
    return result.stdout


def head_commit(repo: Path) -> str:
    commit = _git(repo, "rev-parse", "--verify", "HEAD^{commit}").decode("ascii").strip()
    if not COMMIT_RE.match(commit):
        raise CatalogueError(f"{repo}: HEAD is not a full commit id")
    return commit


def bundle_files(repo: Path, commit: str, path: str) -> list[BundleFile]:
    """The regular files of the bundle `path` at `commit`, sorted by path."""
    if not COMMIT_RE.match(commit):
        raise CatalogueError(f"{commit!r} is not a full commit id")
    if not valid_bundle_path(path):
        raise CatalogueError(f"{path!r} is not a relative bundle path")
    _git(repo, "cat-file", "-e", f"{commit}^{{commit}}")
    listing = _git(repo, "ls-tree", "-r", "-z", "--full-tree", commit, "--", f"{path}/")
    prefix = f"{path}/"
    files: list[BundleFile] = []
    total = 0
    for record in filter(None, listing.split(b"\0")):
        meta, _, raw_name = record.partition(b"\t")
        try:
            mode, kind, obj = meta.decode("ascii").split(" ")
            name = raw_name.decode("utf-8")
        except (UnicodeDecodeError, ValueError) as exc:
            raise CatalogueError(f"{path}: unreadable tree entry at {commit}") from exc
        if mode not in FILE_MODES or kind != "blob":
            raise CatalogueError(f"{name}: only regular files may be in a bundle (mode {mode})")
        if not name.startswith(prefix) or "\n" in name:
            raise CatalogueError(f"{name}: unexpected path")
        data = _git(repo, "cat-file", "blob", obj)
        if len(data) > MAX_FILE_BYTES:
            raise CatalogueError(f"{name}: larger than {MAX_FILE_BYTES} bytes")
        total += len(data)
        files.append(BundleFile(name[len(prefix):], mode, data))
        if len(files) > MAX_FILES or total > MAX_BUNDLE_BYTES:
            raise CatalogueError(f"{path}: bundle larger than {MAX_FILES} files or {MAX_BUNDLE_BYTES} bytes")
    if not any(f.path == MANIFEST for f in files):
        raise CatalogueError(f"{path}: no {MANIFEST} at {commit}")
    return sorted(files, key=lambda f: f.path.encode("utf-8"))


def bundle_digest(files: list[BundleFile]) -> str:
    summary = hashlib.sha256()
    for item in sorted(files, key=lambda f: f.path.encode("utf-8")):
        line = f"{item.mode} {hashlib.sha256(item.data).hexdigest()} {item.path}\n"
        summary.update(line.encode("utf-8"))
    return f"sha256:{summary.hexdigest()}"


def _normalise_addons(addons: object) -> list[dict[str, Any]]:
    if not isinstance(addons, list):
        raise CatalogueError("requires.addons: must be a list")
    result = []
    for neighbour in addons:
        if isinstance(neighbour, str):
            result.append({"name": neighbour, "optional": False})
            continue
        if not isinstance(neighbour, dict) or ("name" in neighbour and "id" in neighbour):
            raise CatalogueError("requires.addons: entries are a name or a mapping with name or id")
        unknown = set(neighbour) - {"name", "id", "version", "optional"}
        if unknown:
            raise CatalogueError(f"requires.addons: unknown field {', '.join(sorted(unknown))}")
        item: dict[str, Any] = {"name": neighbour.get("name", neighbour.get("id"))}
        if "version" in neighbour:
            item["version"] = neighbour["version"]
        item["optional"] = neighbour.get("optional", False)
        result.append(item)
    return result


def describe(repo: Path, commit: str, path: str) -> dict[str, Any]:
    """What an entry copies from the bundle at `commit`: name, version, description,
    requires and the bundle digest."""
    files = bundle_files(repo, commit, path)
    manifest_file = next(f for f in files if f.path == MANIFEST)
    try:
        manifest = yaml.safe_load(manifest_file.data.decode("utf-8"))
    except (UnicodeDecodeError, yaml.YAMLError) as exc:
        raise CatalogueError(f"{path}/{MANIFEST}: not valid YAML") from exc
    if not isinstance(manifest, dict):
        raise CatalogueError(f"{path}/{MANIFEST}: not a mapping")
    raw = manifest.get("requires")
    if not isinstance(raw, dict):
        raise CatalogueError(f"{path}/{MANIFEST}: requires must be a mapping")
    requires: dict[str, Any] = {
        "addon_api": raw.get("addon_api"),
        "papaia_compat": manifest.get("papaia_compat"),
    }
    if "addons" in raw:
        requires["addons"] = _normalise_addons(raw["addons"])
    return {
        "name": manifest.get("name"),
        "version": manifest.get("version"),
        "description": manifest.get("description"),
        "requires": requires,
        "digest": bundle_digest(files),
    }


def verify(item: dict[str, Any], repo: Path) -> list[str]:
    """Differences between a catalogue entry and its bundle in the clone `repo`."""
    source = item["source"]
    try:
        described = describe(repo, source["commit"], source["path"])
    except CatalogueError as exc:
        return [f"{item['name']}: {exc}"]
    return [
        f"{item['name']}: {field} is {item.get(field)!r} in the catalogue but {described[field]!r} in the bundle"
        for field in ("name", "version", "description", "requires", "digest")
        if item.get(field) != described[field]
    ]


def fetch(item: dict[str, Any], repo: Path, into: Path) -> None:
    """Write the bundle of `item` from `repo` into the new or empty directory `into`,
    after its digest matched the catalogue."""
    if into.exists() and (not into.is_dir() or any(into.iterdir())):
        raise CatalogueError(f"{into}: exists and is not an empty directory")
    source = item["source"]
    files = bundle_files(repo, source["commit"], source["path"])
    digest = bundle_digest(files)
    if digest != item["digest"]:
        raise CatalogueError(f"{item['name']}: bundle digest {digest} differs from the catalogue")
    into.mkdir(parents=True, exist_ok=True)
    for bundle_file in files:
        target = into.joinpath(*bundle_file.path.split("/"))
        if into.resolve() not in target.resolve().parents:
            raise CatalogueError(f"{bundle_file.path}: outside the target directory")
        target.parent.mkdir(parents=True, exist_ok=True)
        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
        mode = 0o755 if bundle_file.mode == "100755" else 0o644
        fd = os.open(target, flags, mode)
        with os.fdopen(fd, "wb") as handle:
            handle.write(bundle_file.data)
        os.chmod(target, mode)


# ---------------------------------------------------------------------------
# Compatibility matrix of the core


def _version(value: str) -> tuple[int, int, int]:
    found = VERSION_RE.match(value)
    if not found:
        raise CatalogueError(f"{value!r} is not X.Y.Z")
    return int(found[1]), int(found[2]), int(found[3])


def satisfies(version: str, constraint: str) -> bool:
    if not valid_constraint(constraint):
        raise CatalogueError(f"{constraint!r} is not a version range")
    current = _version(version)
    for part in constraint.split(","):
        found = CONSTRAINT_RE.match(part)
        assert found is not None
        operator, bound = found[1], _version(found[2])
        ok = {
            ">=": current >= bound,
            "<=": current <= bound,
            ">": current > bound,
            "<": current < bound,
            "==": current == bound,
        }[operator]
        if not ok:
            return False
    return True


def matrix(doc: dict[str, Any], core: Path, suite: str | None) -> list[str]:
    """Entries whose version or contract generations fall outside the core's suite row."""
    data = load(core / "compat" / "suite.yaml")
    if suite is None:
        suite = (core / "VERSION").read_text(encoding="utf-8").strip()
    rows = data.get("suites")
    row = next(
        (r for r in rows or [] if isinstance(r, dict) and r.get("suite") == suite), None
    ) if isinstance(rows, list) else None
    if row is None:
        return [f"compat/suite.yaml has no row for suite {suite}"]
    window = row.get("addon_api") or {}
    versions = row.get("versions") or {}
    if not isinstance(window, dict) or not isinstance(versions, dict):
        return [f"compat/suite.yaml: suite {suite} is malformed"]
    lowest, highest = window.get("min"), window.get("current")
    if not isinstance(lowest, int) or not isinstance(highest, int):
        return [f"compat/suite.yaml: suite {suite} has no addon_api window"]
    problems = []
    for item in doc["entries"]:
        name = item["name"]
        outside = [g for g in item["requires"]["addon_api"] if not lowest <= g <= highest]
        if outside:
            problems.append(
                f"{name}: addon_api {outside} is outside {lowest}..{highest} of suite {suite}"
            )
        constraint = versions.get(name)
        if constraint is not None and not satisfies(item["version"], str(constraint)):
            problems.append(f"{name}: {item['version']} is outside {constraint} of suite {suite}")
    return problems


# ---------------------------------------------------------------------------
# Command line


def _requirements_text(requires: dict[str, Any]) -> str:
    parts = [
        "addon_api " + ", ".join(str(g) for g in requires["addon_api"]),
        f"papaia {requires['papaia_compat']}",
    ]
    for neighbour in requires.get("addons", []):
        label = neighbour["name"] + (f" {neighbour['version']}" if "version" in neighbour else "")
        parts.append(label + (" (optional)" if neighbour["optional"] else ""))
    return "; ".join(parts)


def _entry(doc: dict[str, Any], name: str) -> dict[str, Any]:
    for item in doc["entries"]:
        if item["name"] == name:
            return item
    raise CatalogueError(f"{name}: not in the catalogue")


def _repo_pairs(values: list[str]) -> dict[str, Path]:
    pairs = {}
    for value in values:
        name, sep, path = value.partition("=")
        if not sep or not NAME_RE.match(name) or not path:
            raise CatalogueError(f"--repo {value!r}: expected <name>=<path of a clone>")
        pairs[name] = Path(path)
    return pairs


def _load_valid(root: Path) -> dict[str, Any]:
    doc = load(root / CATALOGUE)
    problems = validate(doc, local_addons(root))
    if problems:
        raise CatalogueError("; ".join(problems))
    return doc


def _pin(root: Path, args: argparse.Namespace) -> None:
    doc = _load_valid(root)
    commit = args.commit or head_commit(args.repo)
    described = describe(args.repo, commit, args.path)
    if described["name"] != args.name:
        raise CatalogueError(f"the bundle at {commit} is named {described['name']!r}, not {args.name!r}")
    previous = next((i for i in doc["entries"] if i["name"] == args.name), None)
    title = args.title or (previous or {}).get("title")
    url = args.url or ((previous or {}).get("source") or {}).get("repo")
    if not title or not url:
        raise CatalogueError(f"{args.name}: a new entry needs --title and --url")
    item = {
        "name": args.name,
        "title": title,
        "version": described["version"],
        "description": described["description"],
        "requires": described["requires"],
        "source": {"repo": url, "commit": commit, "path": args.path},
        "digest": described["digest"],
    }
    if previous is None:
        doc["entries"].append(item)
    else:
        doc["entries"][doc["entries"].index(previous)] = item
    write(root, doc)
    print(f"{args.name} {item['version']} {commit} {item['digest']}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="add-on repository (default: this one)")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("check")
    listing = sub.add_parser("list")
    listing.add_argument("--json", action="store_true", help="the entries as JSON")
    pin = sub.add_parser("pin")
    pin.add_argument("name")
    pin.add_argument("--repo", type=Path, required=True, help="clone of the module repository")
    pin.add_argument("--commit", help="full commit id (default: HEAD of the clone)")
    pin.add_argument("--path", default="deploy/papaia-addon", help="bundle path in the repository")
    pin.add_argument("--url", help="https URL of the repository (new entries)")
    pin.add_argument("--title", help="display name (new entries)")
    check_cmd = sub.add_parser("verify")
    check_cmd.add_argument("--repo", action="append", required=True, metavar="NAME=PATH")
    fetch_cmd = sub.add_parser("fetch")
    fetch_cmd.add_argument("name")
    fetch_cmd.add_argument("--repo", type=Path, required=True, help="clone of the module repository")
    fetch_cmd.add_argument("--into", type=Path, required=True, help="new or empty directory")
    matrix_cmd = sub.add_parser("matrix")
    matrix_cmd.add_argument("--core", type=Path, required=True, help="checkout of the core")
    matrix_cmd.add_argument("--suite", help="suite row (default: the core's VERSION)")
    args = parser.parse_args(argv)
    root: Path = args.root

    try:
        if args.command == "check":
            problems = check(root)
        elif args.command == "pin":
            if args.commit is not None and not COMMIT_RE.match(args.commit):
                raise CatalogueError("--commit: a full commit id")
            if args.url is not None and not valid_repo_url(args.url):
                raise CatalogueError("--url: an https URL without credentials, port or query")
            if args.title is not None and not _text(args.title, MAX_TITLE):
                raise CatalogueError(f"--title: one line of at most {MAX_TITLE} characters")
            if not valid_bundle_path(args.path):
                raise CatalogueError("--path: a relative path without `..`")
            _pin(root, args)
            problems = []
        elif args.command == "list":
            doc = _load_valid(root)
            if args.json:
                print(json.dumps(doc["entries"], indent=2, ensure_ascii=False))
            for item in [] if args.json else doc["entries"]:
                print(f"{item['name']} {item['version']} - {item['title']}: {item['description']}")
                print(f"  requires: {_requirements_text(item['requires'])}")
                print(f"  source: {item['source']['repo']} {item['source']['commit']} {item['source']['path']}")
                print(f"  digest: {item['digest']}")
            problems = []
        elif args.command == "verify":
            doc = _load_valid(root)
            problems = []
            for name, repo in _repo_pairs(args.repo).items():
                found = verify(_entry(doc, name), repo)
                problems += found
                if not found:
                    print(f"{name}: matches {_entry(doc, name)['source']['commit']}")
        elif args.command == "fetch":
            doc = _load_valid(root)
            fetch(_entry(doc, args.name), args.repo, args.into)
            print(args.into)
            problems = []
        else:
            problems = matrix(_load_valid(root), args.core, args.suite)
            if not problems:
                print("every entry is inside the suite row of the core")
    except (CatalogueError, OSError) as exc:
        problems = [str(exc)]
    for problem in problems:
        print(f"catalogue: {problem}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
